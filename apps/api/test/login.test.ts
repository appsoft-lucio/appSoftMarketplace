import { test } from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { createServer } from "node:http";
import type { AddressInfo } from "node:net";
import { PGlite } from "@electric-sql/pglite";
import { createLoginService } from "../src/login/service.ts";
import { createApp } from "../src/app.ts";
import { HttpError } from "../src/auth.ts";
import type { Database } from "../src/stores/repository.ts";
const one = "00000000-0000-4000-8000-000000000001";
const two = "00000000-0000-4000-8000-000000000002";
test("usuário: exclusividade atômica, contas antigas, acesso, sigilo do e-mail e limite de tentativas", async t => {
  const db = new PGlite(); t.after(() => db.close());
  await db.exec("CREATE SCHEMA auth; CREATE TABLE auth.users (id uuid PRIMARY KEY, email text UNIQUE, raw_user_meta_data jsonb DEFAULT '{}', deleted_at timestamptz, is_sso_user boolean DEFAULT false)");
  for (const file of ["001_initial.sql", "008_login_names.sql"]) await db.exec((await readFile(new URL(`../../../database/migrations/${file}`,import.meta.url),"utf8")).replace(/^\uFEFF/,""));
  await db.query("INSERT INTO auth.users(id,email,raw_user_meta_data) VALUES ($1,'one@example.test',$2),($3,'two@example.test','{}')", [one,JSON.stringify({username:"Ana.Silva"}),two]);
  const authCalls: string[] = [];
  const service = createLoginService(() => db as unknown as Database, async (email,password) => {
    authCalls.push(email);
    if (email !== "one@example.test" || password !== "abc123") throw new HttpError(401,"Usuário ou senha incorretos.");
    return {access_token:"access",refresh_token:"refresh"};
  });
  assert.deepEqual(await service.available({username:" ANA.SILVA "}), {available:false});
  assert.deepEqual(await service.profile({id:two,email:"",name:""}), {username:null});
  await assert.rejects(db.query("INSERT INTO auth.users(id,email,raw_user_meta_data) VALUES ('00000000-0000-4000-8000-000000000003','third@example.test',$1)",[JSON.stringify({username:"ana.silva"})]));
  assert.equal((await db.query("SELECT 1 FROM auth.users WHERE email='third@example.test'")).rows.length,0);
  await db.query("UPDATE auth.users SET raw_user_meta_data=$1 WHERE id=$2",[JSON.stringify({username:"spoofed"}),one]);
  assert.deepEqual(await service.profile({id:one,email:"",name:""}),{username:"ana.silva"});
  await assert.rejects(service.save({id:two,email:"",name:""},{username:"ANA.SILVA"}),(e:unknown)=>e instanceof HttpError && e.status===409);
  assert.deepEqual(await service.save({id:two,email:"",name:""},{username:"other.user"}),{username:"other.user"});
  assert.deepEqual(await service.login({username:"ANA.SILVA",password:"abc123"}),{access_token:"access",refresh_token:"refresh"});
  await assert.rejects(service.login({username:"ana.silva",password:"wrong"}),/Usuário ou senha incorretos/);
  await assert.rejects(service.login({username:"nonexistent",password:"abc123"}),/Usuário ou senha incorretos/);
  assert.equal(authCalls.at(-1),"unknown-login@appsoft.invalid");
  for (let n=0;n<10;n++) await assert.rejects(service.login({username:"rate.test",password:"wrong"}),/Usuário ou senha incorretos/);
  await assert.rejects(service.login({username:"rate.test",password:"wrong"}),(e:unknown)=>e instanceof HttpError&&e.status===429);
  const server=createServer(createApp({login:service,verifyUser:async()=>({id:two,email:"",name:""}),stores:{list:async()=>[],create:async()=>{throw Error("unused")}}}));
  await new Promise<void>(r=>server.listen(0,"127.0.0.1",r));
  t.after(()=>new Promise<void>(r=>server.close(()=>r())));
  const base=`http://127.0.0.1:${(server.address() as AddressInfo).port}`;
  assert.equal((await fetch(base+"/api/me/username")).status,401);
  const profile=await fetch(base+"/api/me/username",{headers:{Authorization:"Bearer test"}});
  assert.deepEqual(await profile.json(),{username:"other.user"});
  const response=await fetch(base+"/api/auth/username/login",{method:"POST",headers:{"Content-Type":"application/json"},body:JSON.stringify({username:"ana.silva",password:"abc123"})});
  assert.equal(response.status,200);
  assert.equal(response.headers.get("cache-control"),"no-store");
  assert.deepEqual(await response.json(),{access_token:"access",refresh_token:"refresh"});
});
