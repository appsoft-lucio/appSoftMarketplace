import { test } from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";
import { createServer } from "node:http";
import type { AddressInfo } from "node:net";
import { catalog } from "../src/catalog/repository.ts";
import type { Database } from "../src/stores/repository.ts";
import { parseCatalogQuery, priceToCents } from "@appsoft/domain/catalog";
import { cartQuote, publicProducts, publicStore, storeDirectory } from "../src/public/repository.ts";
import { parseCart } from "@appsoft/domain/cart";
import { createApp } from "../src/app.ts";

test("catálogo: subcategorias, filtros combinados e somente lojas/produtos disponíveis", async t => {
  const db = new PGlite(); t.after(() => db.close());
  for (const name of ["001_initial.sql", "002_store_registration.sql", "003_store_admin.sql", "004_catalog_filters.sql"]) await db.exec((await readFile(new URL(`../../../database/migrations/${name}`, import.meta.url), "utf8")).replace(/^\uFEFF/, ""));
  const stores = await db.query<{ id: string }>("INSERT INTO marketplace_v2.stores (name, slug, status) VALUES ('Moda Ana', 'moda-ana', 'approved'), ('Calçados Bia', 'calcados-bia', 'approved'), ('Vencida', 'vencida', 'approved'), ('Suspensa', 'suspensa', 'suspended') RETURNING id");
  const [a, b, expired, suspended] = stores.rows.map(row => row.id);
  for (const id of [a, b, expired, suspended]) await db.query("INSERT INTO marketplace_v2.subscriptions (store_id, billing_months, status, starts_at, ends_at) VALUES ($1, 1, 'active', now() - interval '2 months', CASE WHEN $1::uuid = $2::uuid THEN now() - interval '1 day' ELSE now() + interval '1 month' END)", [id, expired]);
  const categories = await db.query<{ id: string; slug: string }>("SELECT id, slug FROM marketplace_v2.categories");
  const idOf = (slug: string) => categories.rows.find(row => row.slug === slug)!.id;
  const dress = (await db.query<{ id: string }>("INSERT INTO marketplace_v2.products (store_id, category_id, name, price_cents, stock, active) VALUES ($1, $2, 'Vestido floral', 12990, 0, true) RETURNING id", [a, idOf("vestidos")])).rows[0].id;
  await db.query("INSERT INTO marketplace_v2.product_variants (product_id, size, stock) VALUES ($1, 'P', 4), ($1, 'G', 2), ($1, 'M', 0)", [dress]);
  await db.query("INSERT INTO marketplace_v2.products (store_id, category_id, name, price_cents, stock, active) VALUES ($1, $2, 'Tênis leve', 9990, 5, true)", [b, idOf("tenis")]);
  const unavailable = (await db.query<{ id: string }>("INSERT INTO marketplace_v2.products (store_id, category_id, name, price_cents, stock, active) VALUES ($1, $2, 'Sem tamanho disponível', 1000, 20, true) RETURNING id", [a, idOf("vestidos")])).rows[0].id;
  await db.query("INSERT INTO marketplace_v2.product_variants (product_id, size, stock) VALUES ($1, 'XXL', 0)", [unavailable]);
  await db.query("INSERT INTO marketplace_v2.products (store_id, name, price_cents, stock, active) VALUES ($1, 'Loja vencida', 100, 5, true), ($2, 'Loja suspensa', 100, 5, true), ($3, 'Inativo', 100, 5, false)", [expired, suspended, a]);
  const adapter = db as unknown as Database;
  const query = (params: string) => catalog(adapter, parseCatalogQuery(new URLSearchParams(params)));
  const all = await query(""); assert.equal(all.total, 2); assert.equal(all.stores.length, 2); assert.deepEqual(all.sizes, ["G", "P"]);
  assert.equal((await query(`category=${idOf("moda")}`)).total, 2);
  assert.deepEqual((await query(`category=${idOf("moda-feminina")}`)).products.map(p => p.id), [dress]);
  assert.equal((await query("size=M")).total, 0);
  assert.equal((await query("size=P&size=G")).total, 1);
  assert.equal((await query(`store=${b}&size=P`)).total, 0);
  assert.equal((await query(`store=${a}&store=${b}`)).total, 2);
  assert.equal((await query("min=129,90&max=129.90")).total, 1);
  assert.equal((await query("q=floral")).products[0].id, dress);
  assert.deepEqual((await query("sort=price_asc")).products.map(p => p.price_cents), [9990, 12990]);
  assert.deepEqual((await query("sort=price_desc")).products.map(p => p.price_cents), [12990, 9990]);
  await assert.rejects(db.query("UPDATE marketplace_v2.categories SET parent_id = $1 WHERE id = $2", [idOf("vestidos"), idOf("moda")]), /descendente/);
  const directory = await storeDirectory(adapter, "", 1);
  assert.equal(directory.total, 2);
  assert.equal("phone" in directory.stores[0], false);
  assert.equal("owners" in directory.stores[0], false);
  assert.equal(await publicStore(adapter, "vencida"), null);
  assert.equal(await publicStore(adapter, "suspensa"), null);
  assert.equal((await publicProducts(adapter, [dress]))[0].store_slug, "moda-ana");
  const validCart = parseCart([{ productId: dress, size: "P", quantity: 2, price_cents: 1, store_id: expired }]);
  const quote = await cartQuote(adapter, validCart);
  assert.equal(quote.subtotalCents, 25980);
  assert.equal(quote.hasIssues, false);
  assert.equal((await cartQuote(adapter, [{ productId: dress, size: "M", quantity: 1 }])).hasIssues, true);
  assert.equal((await cartQuote(adapter, [{ productId: dress, size: null, quantity: 1 }])).hasIssues, true);
  assert.equal((await cartQuote(adapter, [{ productId: dress, size: "P", quantity: 5 }])).hasIssues, true);
  assert.equal((await cartQuote(adapter, [{ productId: unavailable, size: "XXL", quantity: 1 }])).items[0].product, null);
  const server = createServer(createApp({ verifyUser: async () => { throw new Error("Não deve autenticar catálogo público"); }, stores: { list: async () => [], create: async () => { throw new Error("Não usado"); } }, catalog: { list: q => catalog(adapter, q) }, public: { stores: (search, page) => storeDirectory(adapter, search, page), store: slug => publicStore(adapter, slug), product: async id => (await publicProducts(adapter, [id]))[0] || null, quote: items => cartQuote(adapter, items) } }));
  await new Promise<void>(resolve => server.listen(0, "127.0.0.1", resolve));
  t.after(() => new Promise<void>(resolve => server.close(() => resolve())));
  const base = `http://127.0.0.1:${(server.address() as AddressInfo).port}/api/catalog`;
  assert.equal((await fetch(base)).status, 200);
  const publicBase = base.replace("/api/catalog", "/api/public");
  assert.equal((await fetch(publicBase + "/stores")).status, 200);
  assert.equal((await fetch(publicBase + "/stores/vencida")).status, 404);
  assert.equal((await fetch(publicBase + `/products/${dress}`)).status, 200);
  assert.equal((await fetch(publicBase + "/cart/quote", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(validCart) })).status, 200);
  assert.equal((await fetch(publicBase + "/cart/quote", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify([{ ...validCart[0], quantity: -1 }]) })).status, 400);
  assert.equal((await fetch(base + "?min=200&max=100")).status, 400);
  assert.equal((await fetch(base, { method: "POST" })).status, 405);
});
test("preços e filtros rejeitam valores inválidos sem arredondamento de ponto flutuante", () => {
  assert.equal(priceToCents("0,29"), 29);
  assert.equal(priceToCents("99.9"), 9990);
  for (const value of ["-1", "NaN", "1.001", "1e3"]) assert.throws(() => priceToCents(value));
  for (const value of ["page=0", "category=invalid", "store=invalid", "sort=drop-table", "min=10&max=1"]) assert.throws(() => parseCatalogQuery(new URLSearchParams(value)));
});