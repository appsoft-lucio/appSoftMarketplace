import test from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { createServer } from "node:net";
import { once } from "node:events";
import { DatabaseSync } from "node:sqlite";
import { mkdtemp, readFile, unlink, rmdir } from "node:fs/promises";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { PGlite } from "@electric-sql/pglite";
import { PGLiteSocketServer } from "@electric-sql/pglite-socket";

const external = Boolean(process.env.TEST_DATABASE_URL);

test("PostgreSQL API integration", { timeout: 120000 }, async (t) => {
  let embedded, socket, pool, http;
  const schema = `appsoft_test_${randomUUID().replaceAll("-", "")}`;
  process.env.DATABASE_SCHEMA = schema;
  process.env.JWT_SECRET = "isolated-test-secret";
  process.env.NODE_ENV = "test";
  process.env.VERCEL = "1";
  try {
    if (external) {
      process.env.DATABASE_URL = process.env.TEST_DATABASE_URL;
    } else {
      // Override local credentials before importing application code.
      const reservation = createServer();
      reservation.listen(0, "127.0.0.1");
      await once(reservation, "listening");
      const port = reservation.address().port;
      await new Promise((resolve) => reservation.close(resolve));
      embedded = await PGlite.create();
      socket = new PGLiteSocketServer({
        db: embedded,
        host: "127.0.0.1",
        port,
        maxConnections: 5,
      });
      await socket.start();
      process.env.DATABASE_URL = `postgresql://postgres:postgres@127.0.0.1:${port}/postgres`;
    }
    const database = await import("../src/database.js");
    pool = database.pool;
    const { tables } = database;
    const { migrate } = await import("../src/migrate.js");
    await migrate();
    await migrate(); // Initial migration can be run again without losing data.
    await t.test(
      "SQLite import preserves records and refuses a nonempty destination",
      async () => {
        const directory = await mkdtemp(
          join(tmpdir(), "appsoft-sqlite-fixture-"),
        );
        const path = join(directory, "fixture.db");
        const source = new DatabaseSync(path);
        try {
          const ddl = (
            await readFile(
              new URL("../migrations/001_initial.sql", import.meta.url),
              "utf8",
            )
          ).replaceAll(
            "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
            "INTEGER PRIMARY KEY AUTOINCREMENT",
          );
          source.exec(ddl);
          source.exec(`
          INSERT INTO users (id, name, email, password_hash, role, created_at)
            VALUES (100, 'Imported vendor', 'imported@appsoft.test', 'preserve-this-hash', 'vendor', '2025-01-01 12:00:00');
          INSERT INTO products (id, vendor_id, name, price, category, stock) VALUES (200, 100, 'Imported product', 29.90, 'Test', 7);
          INSERT INTO cart_items (id, user_id, product_id, quantity) VALUES (500, 100, 200, 1);
          INSERT INTO orders (id, customer_id, subtotal, shipping, total) VALUES (300, 100, 29.90, 25, 54.90);
          INSERT INTO order_items (id, order_id, product_id, vendor_id, product_name, unit_price, quantity, subtotal)
            VALUES (400, 300, 200, 100, 'Imported product', 29.90, 1, 29.90);
        `);
          const { importSqlite } = await import("../src/importSqlite.js");
          const counts = await importSqlite(path);
          assert.deepEqual(counts, {
            users: 1,
            products: 1,
            cart_items: 1,
            orders: 1,
            order_items: 1,
          });
          const {
            rows: [imported],
          } = await pool.query(`SELECT * FROM ${tables.users} WHERE id = 100`);
          assert.equal(imported.password_hash, "preserve-this-hash");
          assert.equal(
            imported.created_at.toISOString(),
            "2025-01-01T12:00:00.000Z",
          );
          await assert.rejects(importSqlite(path), /destino vazias/);
          assert.equal(
            source.prepare("SELECT stock FROM products WHERE id = 200").get()
              .stock,
            7,
          );
        } finally {
          source.close();
          await unlink(path);
          await rmdir(directory);
        }
      },
    );
    const { default: app } = await import("../../api/index.js");
    http = app.listen(0, "127.0.0.1");
    await once(http, "listening");
    const base = `http://127.0.0.1:${http.address().port}/api`;
    const request = async (
      path,
      { token, body, method = "GET", status = 200 } = {},
    ) => {
      const response = await fetch(`${base}${path}`, {
        method,
        headers: {
          "Content-Type": "application/json",
          ...(token ? { Authorization: `Bearer ${token}` } : {}),
        },
        ...(body ? { body: JSON.stringify(body) } : {}),
      });
      const data = response.status === 204 ? null : await response.json();
      if (status !== null)
        assert.equal(response.status, status, JSON.stringify(data));
      return { ...data, httpStatus: response.status };
    };
    const account = (name, role = "customer") =>
      request("/auth/register", {
        method: "POST",
        status: 201,
        body: {
          name,
          email: `${name}@appsoft.test`,
          password: "test-password",
          role,
        },
      });
    const vendor = await account("vendor", "vendor");
    const customer = await account("customer");
    const stranger = await account("stranger");
    const productBody = {
      name: "Integration product",
      description: "Test",
      category: "Software",
      price: 49.9,
      stock: 5,
    };
    let product, order;

    await t.test("registration, login and access controls", async () => {
      await request("/health");
      await request("/missing", { status: 404 });
      await request("/auth/register", {
        method: "POST",
        body: {
          name: "Duplicate",
          email: "customer@appsoft.test",
          password: "test-password",
        },
        status: 409,
      });
      await request("/auth/register", {
        method: "POST",
        body: { name: "Invalid", email: "invalid", password: "test-password" },
        status: 400,
      });
      const login = await request("/auth/login", {
        method: "POST",
        body: { email: "customer@appsoft.test", password: "test-password" },
      });
      assert.equal(login.user.id, customer.user.id);
      assert.equal(
        (await request("/auth/me", { token: login.token })).user.email,
        "customer@appsoft.test",
      );
      await request("/auth/login", {
        method: "POST",
        body: { email: "customer@appsoft.test", password: "wrong" },
        status: 401,
      });
      await request("/cart", { status: 401 });
      await request("/products", {
        method: "POST",
        token: customer.token,
        body: productBody,
        status: 403,
      });
      product = (
        await request("/products", {
          method: "POST",
          token: vendor.token,
          body: productBody,
          status: 201,
        })
      ).product;
      assert.equal(product.price, 49.9);
      assert.ok(product.id > 200);
      assert.ok(vendor.user.id > 100);
      assert.equal(
        (await request("/products/mine", { token: vendor.token })).products[0]
          .id,
        product.id,
      );
      await request(`/products/${product.id}`, {
        method: "PUT",
        token: customer.token,
        body: productBody,
        status: 403,
      });
    });

    await t.test("cart quantities, checkout and order visibility", async () => {
      await request("/cart/items", {
        method: "POST",
        token: customer.token,
        body: { productId: product.id, quantity: 1 },
        status: 201,
      });
      const cart = await request(`/cart/items/${product.id}`, {
        method: "PUT",
        token: customer.token,
        body: { quantity: 2 },
      });
      assert.equal(cart.total, 124.8);
      await request(`/cart/items/${product.id}`, {
        method: "PUT",
        token: customer.token,
        body: { quantity: 6 },
        status: 400,
      });
      await request(`/cart/items/${product.id}`, {
        method: "PUT",
        token: customer.token,
        body: { quantity: 0 },
        status: 400,
      });
      order = (
        await request("/orders/checkout", {
          method: "POST",
          token: customer.token,
          status: 201,
        })
      ).order;
      assert.equal(order.total, 124.8);
      assert.equal(order.items[0].quantity, 2);
      assert.equal((await request(`/products/${product.id}`)).product.stock, 3);
      assert.equal(
        (await request("/cart", { token: customer.token })).items.length,
        0,
      );
      assert.equal(
        (await request("/orders/mine", { token: customer.token })).orders[0].id,
        order.id,
      );
      const vendorOrder = (await request("/orders/vendor/mine", { token: vendor.token })).orders[0];
      assert.equal(vendorOrder.id, order.id);
      assert.equal(vendorOrder.customer_name, customer.user.name);
      assert.equal(vendorOrder.vendor_count, 1);
      assert.equal(vendorOrder.items.reduce((sum, item) => sum + item.subtotal, 0), 99.8);
      await request(`/orders/${order.id}`, {
        token: stranger.token,
        status: 404,
      });
      await request("/orders/checkout", {
        method: "POST",
        token: customer.token,
        status: 400,
      });
      assert.equal((await request(`/products/${product.id}`)).product.stock, 3);
    });

    await t.test(
      "async status changes, cancellation and soft delete",
      async () => {
        const paid = await request(`/orders/vendor/${order.id}/status`, {
          method: "PATCH",
          token: vendor.token,
          body: { status: "pago" },
        });
        assert.equal(paid.order.status, "pago");
        const cancelled = await request(`/orders/${order.id}/cancel`, {
          method: "PATCH",
          token: customer.token,
        });
        assert.equal(cancelled.order.status, "cancelado");
        await request(`/orders/${order.id}/cancel`, {
          method: "PATCH",
          token: customer.token,
          status: 400,
        });
        const changed = await request(`/products/${product.id}`, {
          method: "PUT",
          token: vendor.token,
          body: { ...productBody, stock: 4 },
        });
        assert.equal(changed.product.stock, 4);
        const deleted = (
          await request("/products", {
            method: "POST",
            token: vendor.token,
            body: { ...productBody, name: "Delete me" },
            status: 201,
          })
        ).product;
        await request(`/products/${deleted.id}`, {
          method: "DELETE",
          token: vendor.token,
          status: 204,
        });
        await request(`/products/${deleted.id}`, { status: 404 });
      },
    );

    await t.test(
      "checkout rolls back partial writes on database failure",
      async () => {
        const broken = (
          await request("/products", {
            method: "POST",
            token: vendor.token,
            body: { ...productBody, name: "Reject item" },
            status: 201,
          })
        ).product;
        for (const id of [product.id, broken.id]) {
          await request("/cart/items", {
            method: "POST",
            token: customer.token,
            body: { productId: id, quantity: 1 },
            status: 201,
          });
        }
        const countBefore = (
          await pool.query(`SELECT COUNT(*) FROM ${tables.orders}`)
        ).rows[0].count;
        await pool.query(
          `ALTER TABLE ${tables.order_items} ADD CONSTRAINT test_reject_item CHECK (product_name <> 'Reject item')`,
        );
        const failed = await request("/orders/checkout", {
          method: "POST",
          token: customer.token,
          status: 500,
        });
        assert.equal(failed.message, "Erro interno do servidor.");
        assert.equal(
          (await pool.query(`SELECT COUNT(*) FROM ${tables.orders}`)).rows[0]
            .count,
          countBefore,
        );
        assert.equal(
          (await request(`/products/${product.id}`)).product.stock,
          4,
        );
        assert.equal(
          (await request(`/products/${broken.id}`)).product.stock,
          5,
        );
        assert.equal(
          (await request("/cart", { token: customer.token })).items.length,
          2,
        );
        await pool.query(
          `ALTER TABLE ${tables.order_items} DROP CONSTRAINT test_reject_item`,
        );
        await request(`/cart/items/${broken.id}`, {
          method: "DELETE",
          token: customer.token,
        });
        await request("/cart", { method: "DELETE", token: customer.token });
      },
    );

    await t.test(
      "concurrent buyers cannot oversell the last unit",
      { skip: !external },
      async () => {
        const last = (
          await request("/products", {
            method: "POST",
            token: vendor.token,
            body: { ...productBody, stock: 1 },
            status: 201,
          })
        ).product;
        for (const buyer of [customer, stranger]) {
          await request("/cart/items", {
            method: "POST",
            token: buyer.token,
            body: { productId: last.id, quantity: 1 },
            status: 201,
          });
        }
        const results = await Promise.all(
          [customer, stranger].map((buyer) =>
            request("/orders/checkout", {
              method: "POST",
              token: buyer.token,
              status: null,
            }),
          ),
        );
        assert.deepEqual(results.map((r) => r.httpStatus).sort(), [201, 400]);
        assert.equal((await request(`/products/${last.id}`)).product.stock, 0);
      },
    );
  } finally {
    if (http) await new Promise((resolve) => http.close(resolve));
    if (pool) {
      try {
        assert.match(schema, /^appsoft_test_[a-f0-9]{32}$/);
        await pool.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`);
      } finally {
        await pool.end();
      }
    }
    if (socket) await socket.stop();
    if (embedded) await embedded.close();
  }
});
